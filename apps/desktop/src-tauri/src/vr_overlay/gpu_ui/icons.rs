pub fn rasterize_icon_r8(icon: IconId, size_px: u32, stroke_width: f32) -> Vec<u8> {
    let size = size_px.max(1);
    let svg = format!(
        r#"<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 24 24" fill="none" stroke="white" stroke-width="{stroke_width}" stroke-linecap="round" stroke-linejoin="round">{}</svg>"#,
        icon.svg_body()
    );
    let opt = resvg::usvg::Options::default();
    let Ok(tree) = resvg::usvg::Tree::from_str(&svg, &opt) else {
        return vec![0; (size * size) as usize];
    };
    let Some(mut pixmap) = resvg::tiny_skia::Pixmap::new(size, size) else {
        return vec![0; (size * size) as usize];
    };
    resvg::render(
        &tree,
        resvg::tiny_skia::Transform::identity(),
        &mut pixmap.as_mut(),
    );
    pixmap
        .data()
        .as_chunks::<4>()
        .0
        .iter()
        .map(|px| px[3])
        .collect()
}

pub fn rasterize_logo_rgba8(size_px: u32) -> Vec<u8> {
    let size = size_px.max(1);
    let svg = include_str!("../../../../public/logos/VRCS_Logo_Small.svg");
    let opt = resvg::usvg::Options::default();
    let Ok(tree) = resvg::usvg::Tree::from_str(svg, &opt) else {
        return vec![0; (size * size * 4) as usize];
    };
    let Some(mut pixmap) = resvg::tiny_skia::Pixmap::new(size, size) else {
        return vec![0; (size * size * 4) as usize];
    };
    let vb = tree.size();
    let sx = size as f32 / vb.width().max(1.0);
    let sy = size as f32 / vb.height().max(1.0);
    resvg::render(
        &tree,
        resvg::tiny_skia::Transform::from_scale(sx, sy),
        &mut pixmap.as_mut(),
    );
    pixmap.take()
}

#[cfg(all(windows, debug_assertions, feature = "vr-preview"))]
pub fn thumbnail_rgba8() -> (u32, u32, Vec<u8>) {
    let img = tauri::include_image!("icons/128x128@2x.png");
    let mut pixels = img.rgba().to_vec();
    for px in pixels.as_chunks_mut::<4>().0 {
        let a = u32::from(px[3]);
        for ch in &mut px[..3] {
            *ch = ((u32::from(*ch) * a + 127) / 255) as u8;
        }
    }
    (img.width(), img.height(), pixels)
}
